      <h3>Recitals</h3>
      <p>Covered Entity is a HIPAA-covered entity that uses the QBL Alerts service provided by Business Associate to support clinical workflow in labor and delivery settings. In connection with this service, Business Associate may have access to Protected Health Information (&ldquo;PHI&rdquo;) created or maintained by Covered Entity. The parties enter into this Agreement to satisfy the requirements of 45 C.F.R. &sect;&sect; 164.308, 164.310, 164.312, and 164.314.</p>

      <h3>1. Definitions</h3>
      <p>Terms used but not otherwise defined in this Agreement shall have the meanings ascribed to them under HIPAA, the HIPAA Privacy Rule (45 C.F.R. Part 164), and the HIPAA Security Rule, as amended by HITECH.</p>
      <ul>
        <li><strong>PHI</strong> means Protected Health Information as defined under 45 C.F.R. &sect; 160.103.</li>
        <li><strong>ePHI</strong> means Electronic Protected Health Information.</li>
        <li><strong>Breach</strong> has the meaning set forth in 45 C.F.R. &sect; 164.402.</li>
        <li><strong>Services</strong> means the QBL Alerts notification and calculation platform provided by Business Associate.</li>
      </ul>

      <h3>2. Permitted Uses and Disclosures by Business Associate</h3>
      <p>Business Associate may use or disclose PHI only as necessary to provide the Services to Covered Entity, and:</p>
      <ol>
        <li>As required by law;</li>
        <li>For the proper management and administration of Business Associate, provided that disclosures are required by law or Business Associate obtains reasonable assurances of confidentiality;</li>
        <li>To report violations of law to appropriate authorities as permitted by 45 C.F.R. &sect; 164.502(j)(1).</li>
      </ol>
      <p>Business Associate shall not use or disclose PHI in any manner that would violate the HIPAA Privacy Rule if done by Covered Entity.</p>

      <h3>3. Obligations of Business Associate</h3>
      <p>Business Associate agrees to:</p>
      <ol>
        <li>Not use or disclose PHI other than as permitted or required by this Agreement or applicable law;</li>
        <li>Implement appropriate administrative, physical, and technical safeguards to protect ePHI in accordance with 45 C.F.R. &sect;&sect; 164.308, 164.310, and 164.312;</li>
        <li>Report to Covered Entity any use or disclosure of PHI not provided for by this Agreement, including Breaches of Unsecured PHI, without unreasonable delay and in no case later than <strong>60 calendar days</strong> after discovery;</li>
        <li>In accordance with 45 C.F.R. &sect; 164.502(e)(1)(ii), ensure that any subcontractors that create, receive, maintain, or transmit PHI on behalf of Business Associate agree to the same restrictions and conditions that apply to Business Associate;</li>
        <li>Make available PHI in a designated record set to Covered Entity as necessary to satisfy Covered Entity&rsquo;s obligations under 45 C.F.R. &sect; 164.524;</li>
        <li>Make its internal practices, books, and records relating to the use and disclosure of PHI available to the Secretary of the U.S. Department of Health and Human Services for purposes of determining compliance;</li>
        <li>Upon termination of this Agreement, return or destroy all PHI received from, or created or received on behalf of, Covered Entity, to the extent feasible. Where return or destruction is not feasible, Business Associate shall extend the protections of this Agreement to such PHI and limit further use or disclosure;</li>
        <li>Comply with the applicable requirements of the HIPAA Security Rule with respect to ePHI.</li>
      </ol>

      <h3>4. Obligations of Covered Entity</h3>
      <p>Covered Entity agrees to:</p>
      <ol>
        <li>Notify Business Associate of any limitation in its Notice of Privacy Practices that may affect Business Associate&rsquo;s use or disclosure of PHI;</li>
        <li>Notify Business Associate of any changes in, or revocation of, an individual&rsquo;s permission to use or disclose PHI, to the extent it may affect Business Associate&rsquo;s permitted uses or disclosures;</li>
        <li>Not request that Business Associate use or disclose PHI in any manner that would not be permissible under the HIPAA Privacy Rule if done by Covered Entity;</li>
        <li>Train staff on appropriate use of the Service, including the requirement not to enter directly identifying patient information (e.g., name, MRN, date of birth) into the Service unless specifically required and authorized.</li>
      </ol>

      <h3>5. Term and Termination</h3>
      <p>This Agreement shall be effective as of the date last signed and shall remain in effect until the Services agreement between the parties is terminated, or until terminated as follows:</p>
      <ol>
        <li><strong>Termination for Cause:</strong> Either party may terminate this Agreement upon written notice if the other party has materially breached a provision of this Agreement and has not cured such breach within thirty (30) days of written notice;</li>
        <li><strong>Automatic Termination:</strong> This Agreement shall automatically terminate upon termination or expiration of any underlying Services agreement between the parties;</li>
        <li><strong>Effect of Termination:</strong> Upon termination, Business Associate shall return or destroy all PHI as described in Section 3(7) above.</li>
      </ol>

      <h3>6. Miscellaneous</h3>
      <p><strong>Amendment.</strong> The parties agree to amend this Agreement as necessary to comply with changes in HIPAA, HITECH, or applicable regulations. Business Associate may update this Agreement with thirty (30) days written notice; continued use of the Services constitutes acceptance.</p>
      <p><strong>No Third-Party Beneficiaries.</strong> Nothing in this Agreement shall confer any rights or remedies upon any person other than the parties hereto.</p>
      <p><strong>Governing Law.</strong> This Agreement shall be governed by the laws of the State of Texas, without regard to its conflict of law provisions.</p>
      <p><strong>Entire Agreement.</strong> This Agreement, together with any applicable Services agreement, constitutes the entire agreement between the parties with respect to HIPAA compliance and supersedes all prior agreements relating to the subject matter hereof.</p>
      <p><strong>Severability.</strong> If any provision of this Agreement is found to be unenforceable, the remaining provisions shall remain in full force and effect.</p>
      <p><strong>Interpretation.</strong> Any ambiguity in this Agreement shall be resolved in favor of a meaning that permits Covered Entity to comply with HIPAA.</p>

